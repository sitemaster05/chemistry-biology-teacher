-- 1. Материал «География» — был «Биология и география»
update public.materials
set subject = 'География'
where subject = 'Биология и география';

-- 2. Выступление на педсовете о качестве знаний — был «Химия и биология»
--    (если хотите другой предмет — потом поменяйте в админке в один клик)
update public.materials
set subject = 'Химия'
where subject = 'Химия и биология';

-- 3. Экологический вестник «Всемирный день воды» — была «Биология»
update public.materials
set subject = 'Экология'
where subject = 'Биология'
  and title like '%Всемирный день воды%';

-- 4. «Формирование ключевых компетенций на уроках географии...» — была «Биология»
update public.materials
set subject = 'География'
where subject = 'Биология'
  and title like '%Формирование ключевых компетенций%';

